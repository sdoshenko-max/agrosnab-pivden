export function getCityBySlug(slug: string): City | undefined {
  return cities.find(c => c.slug === slug);
}

// Сусідні міста для перелінковки на сторінці міста.
// Беремо 3 найближчих за відстанню до поточного міста.
export function getNeighborCities(currentSlug: string, limit = 3): City[] {
  const current = getCityBySlug(currentSlug);
  if (!current) return [];
  const others = cities.filter(c => c.slug !== currentSlug);
  return others
    .map(c => ({ city: c, dist: Math.abs(c.distanceKm - current.distanceKm) }))
    .sort((a, b) => a.dist - b.dist)
    .slice(0, limit)
    .map(x => x.city);
}
