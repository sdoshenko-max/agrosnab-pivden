// Реальна відстань між двома точками на сфері (формула haversine, км).
// Використовується для перелінковки — щоб сусіди визначалися географічно,
// а не за абсолютною відстанню від нашого складу в Миколаєві.
function haversineKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const R = 6371; // радіус Землі, км
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

// Сусідні міста для перелінковки на сторінці міста.
// Беремо `limit` найближчих за реальною відстанню до поточного міста (haversine).
export function getNeighborCities(currentSlug: string, limit = 4): City[] {
  const current = getCityBySlug(currentSlug);
  if (!current) return [];
  return cities
    .filter(c => c.slug !== currentSlug)
    .map(c => ({ city: c, dist: haversineKm(current.coordinates, c.coordinates) }))
    .sort((a, b) => a.dist - b.dist)
    .slice(0, limit)
    .map(x => x.city);
}
