export const inferCategoryFromAI = (ai) => {
  if (!ai) return null;
  for (const [re, cat] of AI_TO_CATEGORY) {
    if (re.test(ai)) return cat;
  }
  return null;
};

// === Inline-категорія (для Himagro, Укравіт): як розпізнати рядок-роздільник ===
export const isCategoryRow = (cells) => {
  const s = cells.map(c => String(c).trim().toUpperCase().replace(/\s/g, "")).join(" ");
  if (/ГЕРБІЦИД|ГЕРБИЦИД/.test(s)) return "herbitsydy";
  if (/ФУНГІЦИД|ФУНГИЦИД/.test(s)) return "funhitsydy";
  if (/ІНСЕКТИЦ|ИНСЕКТИЦ|АКАРИЦ/.test(s)) return "insektitsydy";
  if (/ПРОТРУЙ|ПРОТРАВИ/.test(s)) return "protruyniky";
  if (/ДЕСИКАНТ/.test(s)) return "desykanty";
  if (/РЕГУЛЯТ|МІКРОДОБ|МИКРОДОБ|АДʼЮВАН|АД'ЮВАН|АДЪЮВАН|ПРИЛИПАЧ|ПАВ|ПАР/.test(s)) return "regulyatory";
  if (/РОДЕНТ/.test(s)) return "rodentytsydy";
  return null;
};

