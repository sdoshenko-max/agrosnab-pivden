function field(line, name) {
  // витягує "name: \"value\"" або "name: value" (для чисел/масивів — нам не треба)
  const re = new RegExp(`${name}:\\s*"([^"]*)"`);
  const m = line.match(re);
  return m ? m[1] : "";
}

