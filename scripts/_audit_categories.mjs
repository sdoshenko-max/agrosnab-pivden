// Категорії, що залишаються
const KEEP = new Set(["H", "F", "I"]);
// Перевагу при кількох знахідках: якщо є X — видалити; якщо змішане з протруйником — на видалення (бо протруйники теж видаляємо)

function classify(ai) {
  const norm = (ai || "").toLowerCase().replace(/['ʼ`]/g, "");
  const hits = new Set();
  for (const [key, code] of dict) {
    if (norm.includes(key)) hits.add(code);
  }
  return [...hits];
}

// Підрахунок поточних категорій
const byGroup = {};
for (const p of products) {
  byGroup[p.groupSlug] = (byGroup[p.groupSlug] || 0) + 1;
}

// Дерево рішень — кожному SKU присвоюємо decision: "KEEP" | "DELETE" | { type: "EDIT", to: "H"|"F"|"I" }
function decide(p) {
  const codes = classify(p.activeIngredient);
  const current = slugToCode[p.groupSlug] || "?";
  const codeSet = new Set(codes);
  const codesHFI = codes.filter(c => KEEP.has(c));

  // Видалення-маркери
  if (codeSet.has("X")) return { decision: "DELETE", reason: "адʼювант/родентицид/біопрепарат/фумігант", codes };
  if (["D", "R", "P"].includes(current)) return { decision: "DELETE", reason: `категорія ${codeToName[current]} видаляється`, codes };
  if (codes.length > 0 && codesHFI.length === 0) return { decision: "DELETE", reason: `д.р. → ${codes.map(c => codeToName[c]).join("/")}`, codes };
  if (codesHFI.includes("I") && codesHFI.includes("F")) return { decision: "DELETE", reason: "інсекто-фунгіцидний (протруйник насіння)", codes };

  // Збереження або правка
  if (codesHFI.length === 0) {
    // не впізнано — довіряємо поточній категорії, якщо вона H/F/I
    if (KEEP.has(current)) return { decision: "KEEP", reason: "категорія H/F/I + д.р. не впізнано (трактуємо як OK)", codes };
    return { decision: "DELETE", reason: "категорія не H/F/I і д.р. не впізнано", codes };
  }
  // codesHFI має 1 або 2 елементи (без I+F)
  if (codesHFI.includes(current)) return { decision: "KEEP", reason: `OK: current ${current} ∈ {${codesHFI.join(",")}}`, codes };
  // Правка: беремо перший з codesHFI
  return { decision: "EDIT", to: codesHFI[0], reason: `${codeToName[current]} → ${codeToName[codesHFI[0]]}`, codes };
}

